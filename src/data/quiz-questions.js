export const getRandomQuestions = (count = 20, filters = {}) => {
  let pool = [...QUIZ_QUESTIONS];
  if (filters.category) pool = pool.filter(q => q.category === filters.category);
  if (filters.difficulty) pool = pool.filter(q => q.difficulty === filters.difficulty);
  if (filters.mythBustersOnly) pool = pool.filter(q => q.isMythBuster);
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(count, pool.length));
};

export const getQuizStats = (questions, answers) => {
  const correct = answers.filter((a, i) => a === questions[i].correct).length;
  const total = questions.length;
  const percentage = Math.round((correct / total) * 100);
  const categoryBreakdown = {};
  questions.forEach((q, i) => {
    if (!categoryBreakdown[q.category]) categoryBreakdown[q.category] = { correct: 0, total: 0 };
    categoryBreakdown[q.category].total++;
    if (answers[i] === q.correct) categoryBreakdown[q.category].correct++;
  });
  return { correct, total, percentage, categoryBreakdown, grade: getGrade(percentage) };
};

const getGrade = (pct) => {
  if (pct >= 85) return { label: "Election Expert", color: "#2D5A3D", emoji: "🏆" };
  if (pct >= 60) return { label: "Informed Citizen", color: "#2D7D9A", emoji: "🎖️" };
  return { label: "Novice Voter", color: "#6B6560", emoji: "📚" };
};

